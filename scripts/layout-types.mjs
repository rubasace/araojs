// The library's layouts and their parameters, as types: writes src/components/library-layouts.ts
// from layouts/ (one CSS file per layout; its parameters are the tokens it reads, as
// vite/layout-params.js finds them, which the Vite plugin uses for a project's layouts too).
// `npm run build` runs it first, so the types the build checks and ships are the CSS's; the file
// is committed, so a type check of the source needs no build. Written only if its text changed.
// A token of the library's that is no attribute (a name HTML, Vue or Slide already gives a
// meaning, or not lower-case kebab-case) stops it: rename the token. scripts/bundle-types.mjs
// checks the shipped types against layouts/ again.
//   node scripts/layout-types.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { layoutParams, paramsType } from '../vite/layout-params.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, 'src/components/library-layouts.ts')
const names = (await readdir(resolve(root, 'layouts'))).filter((f) => f.endsWith('.css')).map((f) => f.slice(0, -4)).sort()
const entries = []
const wrong = []
for (const name of names) {
  const { params, skipped } = layoutParams(await readFile(resolve(root, 'layouts', `${name}.css`), 'utf8'), name)
  for (const s of skipped) wrong.push(`  layouts/${name}.css: --ar-layout-${name}-${s.thing}: ${s.why}`)
  entries.push(`  ${/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`}: ${paramsType(name, params, '  ')}\n`)
}
if (wrong.length) {
  console.error(`[arao] a library layout's token is no attribute of Slide: rename it\n${wrong.join('\n')}`)
  process.exit(1)
}
const text = `// Generated by scripts/layout-types.mjs from layouts/ (npm run build runs it): do not edit.
// The library's layouts, and the parameters each takes: an attribute of Slide per token its CSS
// reads, --ar-layout-<name>-<thing>, named <thing> (camelCase here, as Vue names a prop written
// in kebab-case: footer-bg is footerBg), its value a string the slide sets as that token.
// default is the layout of a Slide without one, with no CSS and no parameters.
export interface LibraryLayouts {
  default: {}
${entries.join('')}}
`
let was = null
try {
  was = (await readFile(out, 'utf8')).replace(/\r\n/g, '\n')
} catch {
  // not written yet
}
if (was !== text) {
  await writeFile(out, text)
  console.log(`[arao] wrote ${out.slice(root.length + 1)}`)
}
