// The library's layouts, as types: writes src/components/library-layouts.ts from layouts/ (one CSS
// file per layout): what each one says of itself, its parameters (the tokens it reads) and its
// zones, as vite/layout-docs.js reads them, which the Vite plugin uses for a project's layouts too.
// `npm run build` runs it first, so the types the build checks and ships are the CSS's; the file
// is committed, so a type check of the source needs no build. Written only if its text changed.
// A library layout documents itself in full, and this stops where one does not: a file with no
// doc block, or with no summary or no example in it, a parameter or a zone with no description, a
// problem of its doc block (an unknown tag, a @param naming no token…), a colour or a length its
// CSS writes as a literal instead of a token (vite/layout-literals.js), or a token that is no
// attribute (a name HTML, Vue or Slide already gives a meaning, or not lower-case kebab-case:
// rename the token). CI checks that the committed file is what this writes (git diff after the
// build, .github/workflows/ci.yml): a layout's CSS changed without its types fails there.
//   node scripts/layout-types.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_LAYOUT, describeLayout, layoutEntry, zonesEntry } from '../vite/layout-docs.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, 'src/components/library-layouts.ts')
const names = (await readdir(resolve(root, 'layouts'))).filter((f) => f.endsWith('.css')).map((f) => f.slice(0, -4)).sort()
const infos = [DEFAULT_LAYOUT]
const wrong = []
for (const name of names) {
  const info = describeLayout(await readFile(resolve(root, 'layouts', `${name}.css`), 'utf8'), name)
  const at = `  layouts/${name}.css:`
  if (!info.documented) wrong.push(`${at} no doc block (a /** … */ comment the file starts with: vite/layout-docs.js)`)
  else {
    if (!info.summary) wrong.push(`${at} its doc block has no summary line`)
    if (!info.example) wrong.push(`${at} its doc block has no @example`)
    for (const p of info.params) if (!p.description) wrong.push(`${at} no @param ${p.thing}: --ar-layout-${name}-${p.thing} is not described`)
    for (const z of info.zones) if (!z.description) wrong.push(`${at} no @zone ${z.name}: its CSS styles .ar-zone-${z.name}, which is not described`)
  }
  for (const p of info.problems) wrong.push(`${at} ${p}`)
  for (const s of info.skipped) wrong.push(`${at} --ar-layout-${name}-${s.thing}: ${s.why}: rename the token`)
  infos.push(info)
}
if (wrong.length) {
  console.error(`[arao] a library layout is not documented as it must be, writes a literal colour or length, or its token is no attribute of Slide\n${wrong.join('\n')}`)
  process.exit(1)
}
const text = `// Generated by scripts/layout-types.mjs from layouts/ (npm run build runs it): do not edit.
// The library's layouts, each with what its CSS file's doc block says of it (vite/layout-docs.js):
// - LibraryLayouts: the attributes a slide of each takes: layout (its name, documented: an editor
//   shows that on hovering layout="…"), and one per token its CSS reads, --ar-layout-<name>-<thing>,
//   named <thing> (camelCase here, as Vue names a prop written in kebab-case: footer-bg is footerBg),
//   its value a string the slide sets as that token;
// - LibraryLayoutZones: the zones each places, its named templates besides #title (Slide's types
//   make each member a slot).
// default is the layout of a Slide without one, with no CSS, no parameters and no zones.
export interface LibraryLayouts {
${infos.map((i) => layoutEntry(i, '  ')).join('')}}

export interface LibraryLayoutZones {
${infos.map((i) => zonesEntry(i, '  ')).join('')}}
`
let was = null
try {
  was = (await readFile(out, 'utf8')).replace(/\r\n/g, '\n')
} catch {
  // not written yet
}
if (was !== text) {
  await writeFile(out, text)
  console.log(`[arao] wrote ${out.slice(root.length + 1)}`)
}
